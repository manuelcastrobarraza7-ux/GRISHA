export type MoleculeCategory = 'salts' | 'alcohols' | 'hydrocarbons' | 'complex_organics' | 'triglycerides' | 'metallurgy_fluxes' | 'iodates';

export interface MoleculeAtom {
  id: string;
  symbol: string;
  name: string;
  color: string;
  radiusVdw: number; // in pm (for space-filling)
  radiusCovalent: number; // in pm
  // 2D diagram coordinates (schematic canvas/SVG)
  x2d: number;
  y2d: number;
  // 3D spatial coordinates (in Angstroms, Å)
  x3d: number;
  y3d: number;
  z3d: number;
  formalCharge?: number;
  partialCharge?: 'δ+' | 'δ-' | '0' | '+1' | '-1' | '+2' | '-2';
  lonePairs?: number;
  hybridization?: 'sp³' | 'sp²' | 'sp' | 'iónico' | 'coordinado';
  role?: string;
  electronegativity?: number;
}

export interface MoleculeBond {
  from: string;
  to: string;
  order: 1 | 2 | 3 | 'aromatic' | 'ionic' | 'hydrogen';
  lengthPm?: number;
  description: string;
}

export interface StepAnalysis {
  stepNumber: number;
  title: string;
  subtitle: string;
  explanation: string;
  activeAtomIds: string[];
  activeBondIndices: number[];
  chemicalPrinciple: string;
}

export interface MoleculeData {
  id: string;
  name: string;
  iupacName: string;
  formula: string;
  category: MoleculeCategory;
  categoryLabel: string;
  molarMass: number;
  state: 'sólido' | 'líquido' | 'gas';
  geometry: string;
  dipoleMomentD: number;
  description: string;
  biologicalOrIndustrialRole: string;
  solubilityInWater: string;
  boilingPoint?: string;
  meltingPoint?: string;
  atoms: MoleculeAtom[];
  bonds: MoleculeBond[];
  stepByStepAnalysis: StepAnalysis[];
  rotationalOrConformationalNote?: string;
}

